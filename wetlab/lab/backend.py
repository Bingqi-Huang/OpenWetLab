"""Backend protocol shared by the real MQTT island and the virtual SimPy island."""

from typing import Any, Protocol


class Backend(Protocol):
    closed_skills: set[str]

    def call(
        self,
        device_code: str,
        action: str,
        params: dict[str, Any],
        timeout_s: float,
        operation_id: str | None = None,
    ) -> dict[str, Any]:
        """Send one low-level command and wait for its final result.

        `operation_id` is generated by `Lab` and used as the MQTT `requestId` on real hardware.
        Raises DeviceFailed if the device reports failure, NoResult if no result arrives in time.
        """

    def state(self) -> dict[str, Any]:
        """Return island telemetry and gateway health.

        Format:
            {device_code: {prop: value, "_age_s": float, "_error": str | None},
             "_gateway": {"online": bool, "busy_by_others": bool}}
        """

    def now(self) -> float:
        """Seconds since the epoch on this island's clock."""

    def sleep(self, seconds: float) -> None:
        """Advance or wait `seconds` on this island's clock."""
